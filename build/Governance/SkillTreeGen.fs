module FS.Skia.UI.Build.SkillTreeGen

open System
open System.Text

type SkillFile =
    { Slug: string
      RelPath: string
      Bytes: byte[] }

type GenPlanEntry =
    { DerivedRelPath: string
      Bytes: byte[] }

type SkillTreePlan =
    { Entries: GenPlanEntry list
      ManifestRelPath: string
      ManifestBytes: byte[] }

type SkillCurrency =
    { StaleSlugs: string list
      MissingDerived: string list
      OrphanDerived: string list }

let canonicalRoot = ".agents/skills"
let derivedRoot = ".claude/skills"

let private regenCommand = "./fake.sh build -t RefreshSurfaceBaselines"

let private manifestName = "GENERATED.md"

let derivedRelPath (canonicalRelPath: string) =
    // Normalize separators to forward slash, then swap only the leading tree root.
    let normalized = canonicalRelPath.Replace('\\', '/')

    if normalized.StartsWith(canonicalRoot + "/", StringComparison.Ordinal) then
        derivedRoot + normalized.Substring(canonicalRoot.Length)
    elif normalized = canonicalRoot then
        derivedRoot
    else
        // Defensive: a path outside the canonical root is a generator error, not a
        // silently mis-translated write (Principle VII).
        failwithf "SkillTreeGen.derivedRelPath: %s is not under the canonical tree root %s" canonicalRelPath canonicalRoot

/// Extract the skill slug (the directory segment immediately under `skills/`) from a
/// repo-relative tree path. Used only for human-facing currency reporting.
let private slugOfPath (relPath: string) =
    let segments = relPath.Replace('\\', '/').Split('/')

    match segments |> Array.tryFindIndex (fun s -> s = "skills") with
    | Some i when i + 1 < segments.Length -> segments.[i + 1]
    | _ -> relPath

let renderManifest () : byte[] =
    let sb = StringBuilder()
    sb.Append("# GENERATED — do not edit.\n") |> ignore
    sb.Append("#\n") |> ignore
    sb.Append("# This skill tree (.claude/skills/**) is generated by enumeration from the\n") |> ignore
    sb.Append("# canonical Codex source tree .agents/skills/** by FS.Skia.UI.Build.SkillTreeGen\n") |> ignore
    sb.Append("# (feature 044). Every SKILL.md here is byte-identical to its canonical\n") |> ignore
    sb.Append("# counterpart; edit the canonical file under .agents/skills/ instead.\n") |> ignore
    sb.Append("#\n") |> ignore
    sb.Append(sprintf "# Canonical source: %s/\n" canonicalRoot) |> ignore
    sb.Append(sprintf "# Regenerate via: %s\n" regenCommand) |> ignore
    Encoding.UTF8.GetBytes(sb.ToString())

let plan (canonical: SkillFile list) : SkillTreePlan =
    if List.isEmpty canonical then
        failwith "SkillTreeGen.plan: the canonical skill tree is empty — refusing to emit a partial derived tree (Principle VII). Check that .agents/skills/**/SKILL.md exists."

    for f in canonical do
        if isNull (box f.Bytes) then
            failwithf "SkillTreeGen.plan: canonical file %s is unreadable (null bytes) — refusing to emit a partial derived tree (Principle VII)." f.RelPath

    let entries =
        canonical
        |> List.map (fun f ->
            { DerivedRelPath = derivedRelPath f.RelPath
              Bytes = f.Bytes })

    { Entries = entries
      ManifestRelPath = derivedRoot + "/" + manifestName
      ManifestBytes = renderManifest () }

let private bytesEqual (a: byte[]) (b: byte[]) =
    a.Length = b.Length && Array.forall2 (=) a b

let currency (plan: SkillTreePlan) (derived: SkillFile list) : SkillCurrency =
    let derivedByPath =
        derived
        |> List.map (fun f -> f.RelPath.Replace('\\', '/'), f.Bytes)
        |> Map.ofList

    let expectedPaths =
        (plan.ManifestRelPath :: (plan.Entries |> List.map (fun e -> e.DerivedRelPath)))
        |> List.map (fun p -> p.Replace('\\', '/'))
        |> Set.ofList

    let staleFromEntries =
        plan.Entries
        |> List.choose (fun e ->
            let key = e.DerivedRelPath.Replace('\\', '/')

            match derivedByPath.TryFind key with
            | Some bytes when not (bytesEqual bytes e.Bytes) -> Some(slugOfPath e.DerivedRelPath)
            | _ -> None)

    let manifestKey = plan.ManifestRelPath.Replace('\\', '/')

    let staleManifest =
        match derivedByPath.TryFind manifestKey with
        | Some bytes when not (bytesEqual bytes plan.ManifestBytes) -> [ manifestName ]
        | _ -> []

    let missing =
        (plan.ManifestRelPath :: (plan.Entries |> List.map (fun e -> e.DerivedRelPath)))
        |> List.filter (fun p -> not (derivedByPath.ContainsKey(p.Replace('\\', '/'))))

    let orphans =
        derived
        |> List.map (fun f -> f.RelPath.Replace('\\', '/'))
        |> List.filter (fun p -> not (expectedPaths.Contains p))

    { StaleSlugs = (staleFromEntries @ staleManifest) |> List.distinct
      MissingDerived = missing |> List.distinct
      OrphanDerived = orphans |> List.distinct }

let isCurrent (currency: SkillCurrency) =
    List.isEmpty currency.StaleSlugs
    && List.isEmpty currency.MissingDerived
    && List.isEmpty currency.OrphanDerived

let currencyDrift (currency: SkillCurrency) : string option =
    if isCurrent currency then
        None
    else
        let parts =
            [ if not (List.isEmpty currency.StaleSlugs) then
                  yield sprintf "stale derived skills (bytes differ from canonical): %s" (String.concat ", " currency.StaleSlugs)
              if not (List.isEmpty currency.MissingDerived) then
                  yield sprintf "missing derived files: %s" (String.concat ", " currency.MissingDerived)
              if not (List.isEmpty currency.OrphanDerived) then
                  yield sprintf "orphan derived files with no canonical source: %s" (String.concat ", " currency.OrphanDerived) ]

        Some(
            sprintf
                "SkillSyncCheck: the generated %s tree is not a current reproduction of the canonical %s source — %s. Regenerate via %s."
                derivedRoot
                canonicalRoot
                (String.concat "; " parts)
                regenCommand)
